"""Small structural contracts for custom backends, ranking, policy and logging."""
from typing import Any, Mapping, Protocol


class ModelAdapter(Protocol):
    def new_model(self) -> Any: ...
    def fit(self, model: Any, X: Any, y: Any, eval_set: tuple) -> None: ...
    def predict(self, model: Any, X: Any) -> Any: ...
    def classes(self, model: Any) -> Any: ...
    def feature_count(self, model: Any) -> int: ...
    def validate_full_model(self, model: Any) -> None: ...


class ShapProvider(Protocol):
    def feature_shap(self, model: Any, X: Any, y: Any) -> Any:
        """Return signed contributions of shape (samples, outputs, features)."""
        ...


class CVRefitAdapter(ModelAdapter, Protocol):
    """Additional capabilities required only by external-fold fit_cv()."""

    def best_rounds(self, model: Any) -> int:
        """One-based boosting rounds at the best Validation-loss checkpoint."""
        ...

    def refit(self, X: Any, y: Any, rounds: int) -> Any:
        """Return a fresh model trained on all development, with no eval_set."""
        ...


class ClassificationPredictor(Protocol):
    """Evaluation capability; not required by the selector's ModelAdapter."""
    def predict(self, model: Any, X: Any) -> Any: ...
    def classes(self, model: Any) -> Any: ...
    def predict_proba(self, model: Any, X: Any) -> Any: ...


class GroupRanker(Protocol):
    def rank(self, adapter: ShapProvider, model: Any, X: Any, y: Any,
             groups: Mapping[int, tuple[int, ...]]) -> Mapping[int, float]: ...


class QualityPolicy(Protocol):
    def thresholds(self, baseline: Any) -> Any: ...
    def evaluate(self, scores: Any, thresholds: Any) -> Any: ...


class RunRecorder(Protocol):
    def record(self, event: Mapping[str, Any]) -> None:
        """Observe a detached event; never mutate selection state."""
        ...
